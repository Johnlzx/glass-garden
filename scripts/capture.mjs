import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
import fs from 'node:fs/promises';
const systemChrome=process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser=await chromium.launch({headless:true,...(existsSync(systemChrome)?{executablePath:systemChrome}:{})});
const page=await browser.newPage({viewport:{width:1200,height:1024},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto((process.env.APP_URL || 'http://127.0.0.1:5177/')+'?still');
await page.waitForFunction(()=>Boolean(window.glass));
await page.evaluate(()=>{document.querySelectorAll('dialog').forEach(d=>d.close());window.glass.setPlaying(false);window.glass.setTime(0);});
await page.screenshot({path:'analysis/candidate/desktop.png'});
for(const t of [0,1,2,3,4,5,6,7]) {
 await page.evaluate(t=>{window.glass.setTime(t);document.querySelector('.glass-ui').style.display='none';},t);
 await page.screenshot({path:`analysis/candidate/frame-${t}.png`});
}
await page.evaluate(()=>document.querySelector('.glass-ui').style.display='');
await page.getByRole('button',{name:'Settings',exact:true}).click();
await page.waitForTimeout(260);
await page.screenshot({path:'analysis/candidate/settings.png'});
await page.selectOption('#glass-preset','fluted');
const fluted=await page.evaluate(()=>window.glass.getState());
await page.getByRole('button',{name:'Reset',exact:true}).click();
const reset=await page.evaluate(()=>window.glass.getState());
await page.getByRole('button',{name:'Close settings'}).click();
await page.locator('#scene').focus();
await page.keyboard.press('Space');
await page.waitForTimeout(150);
const playing=await page.evaluate(()=>window.glass.getState().playing);
await page.keyboard.press('Space');
await page.keyboard.press('h');
const hidden=await page.locator('.glass-ui').evaluate(e=>e.classList.contains('ui-hidden'));
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'View the background image'}).click();
const sourceOpen=await page.locator('.source-dialog').evaluate(e=>e.open);
await page.keyboard.press('Escape');
await page.mouse.move(900,500);await page.waitForTimeout(500);
const light=await page.evaluate(()=>window.glass.getState().light);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'analysis/candidate/mobile.png'});
await page.getByRole('button',{name:'Settings',exact:true}).click();
await page.waitForTimeout(260);
await page.screenshot({path:'analysis/candidate/mobile-settings.png'});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const downloadEvent=page.waitForEvent('download');
await page.getByRole('button',{name:'Save an image',exact:true}).click();
const download=await downloadEvent;
await download.saveAs('analysis/candidate/exported.png');
const exportName=download.suggestedFilename();
await page.getByRole('button',{name:'Close settings'}).click();
await page.locator('.sound-button').click();
await page.waitForFunction(()=>document.querySelector('.sound-button').getAttribute('aria-pressed')==='true');
const soundEnabled=await page.locator('.sound-button').getAttribute('aria-pressed');
await page.locator('.sound-button').click();
await page.goto((process.env.APP_URL || 'http://127.0.0.1:5177/')+'?still&clean');
await page.waitForFunction(()=>Boolean(window.glass));
const cleanInert=await page.locator('.glass-toolbar').evaluate(e=>e.inert);
await page.keyboard.press('Escape');
const cleanRestored=await page.locator('.glass-ui').evaluate(e=>!e.classList.contains('ui-hidden'));
if(exportName!=='glass-garden.png'||soundEnabled!=='true'||!cleanInert||!cleanRestored)throw new Error('Extended interaction failure');

if(errors.length || !playing || !hidden || !sourceOpen || overflow || fluted.settings.preset!=='fluted' || reset.settings.preset!=='wired') throw new Error('Interaction check failed: '+JSON.stringify({errors,playing,hidden,sourceOpen,overflow}));
await fs.writeFile('analysis/browser-checks.json',JSON.stringify({errors,fluted,reset,spaceStarts:playing,hideShortcut:hidden,sourceModal:sourceOpen,pointerLight:light,mobileOverflow:overflow,exportName,soundEnabled,cleanInert,cleanRestored},null,2));
await browser.close();
console.log(JSON.stringify({errors,fluted:fluted.settings.preset,reset:reset.settings.preset,spaceStarts:playing,hideShortcut:hidden,sourceModal:sourceOpen,mobileOverflow:overflow}));
